import React from 'react';
import { HelpCircle } from 'lucide-react';
import type { Vocabulary } from '../../types';

interface WordImageProps {
  word?: Vocabulary | { english?: string; imageUrl?: string };
  imageUrl?: string;
  altText?: string;
  className?: string;
}

/**
 * WordImage: Renders the word illustration without duplicate pill label.
 * Specifically masks/crops the bottom 24% of generated SVG data cards
 * which previously contained hardcoded 7px pill labels like "TEACHER", "GIRL", "BOY".
 */
export const WordImage: React.FC<WordImageProps> = ({
  word,
  imageUrl: propUrl,
  altText,
  className = '',
}) => {
  const url = propUrl || word?.imageUrl || '';
  const alt = altText || word?.english || 'Hình ảnh từ vựng';

  // Check if image is an inline SVG card generated by seed containing the bottom label pill
  const isSvgCardWithLabel = url.startsWith('data:image/svg+xml') && url.includes('%3Crect');

  if (!url) {
    return (
      <div className={`w-full h-full flex items-center justify-center ${className}`}>
        <span className="text-6xl sm:text-7xl select-none filter drop-shadow">🌟</span>
      </div>
    );
  }

  return (
    <div className={`w-full h-full relative overflow-hidden flex items-center justify-center ${className}`}>
      {isSvgCardWithLabel ? (
        // Scale and shift up to completely hide the bottom label pill
        <div className="w-full h-full relative overflow-hidden flex items-center justify-center rounded-2xl">
          <img
            src={url}
            alt={alt}
            className="w-full h-full object-cover pointer-events-none filter drop-shadow-md"
            style={{
              // Zoom slightly and offset up to hide bottom pill (y: 186-224px)
              transform: 'scale(1.22) translateY(-4%)',
              clipPath: 'inset(0% 0% 16% 0% round 16px)',
            }}
            loading="eager"
          />
        </div>
      ) : (
        <img
          src={url}
          alt={alt}
          className="max-w-full max-h-full object-contain pointer-events-none filter drop-shadow-md rounded-2xl"
          loading="eager"
        />
      )}
    </div>
  );
};
